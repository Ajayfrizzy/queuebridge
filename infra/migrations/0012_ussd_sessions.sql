-- 0012_ussd_sessions.sql — M6.2 USSD sessions, facility access codes, USSD ticket channel
-- (REQ-F12; design §8 / §16.8 / §17.3; ADR-009). Additive: no table or column is dropped or
-- renamed and no data is removed. Two constraints are relaxed or widened, which is how earlier
-- milestones added channels (0009): `ussd_sessions.facility_id` may be NULL until the visitor
-- has entered a facility code, and `tickets.created_channel` also accepts 'ussd'.
-- Nothing read or wrote `ussd_sessions` before M6.2 (0001 created it), so no row exists to
-- migrate.

-- ---------------------------------------------------------------------------
-- 1. Server-side USSD sessions (keyed by the provider session id's keyed hash)
-- ---------------------------------------------------------------------------
-- A session starts before the facility is known (the visitor types its code first)
ALTER TABLE ussd_sessions ALTER COLUMN facility_id DROP NOT NULL;
-- tenant scope, set together with facility_id (always filtered by both)
ALTER TABLE ussd_sessions ADD COLUMN IF NOT EXISTS organization_id UUID
  REFERENCES organizations (id) ON DELETE CASCADE;
-- keyed hash (HMAC, purpose-derived key) of the subscriber number: per-phone join limit,
-- recovery throttle source and session ownership; the number itself is never stored
ALTER TABLE ussd_sessions ADD COLUMN IF NOT EXISTS msisdn_hash TEXT;
-- the last provider step processed (number of inputs), for in-order processing and replays
ALTER TABLE ussd_sessions ADD COLUMN IF NOT EXISTS step INTEGER NOT NULL DEFAULT 0;
-- hash of the last processed input chain: a repeated callback returns the stored response
ALTER TABLE ussd_sessions ADD COLUMN IF NOT EXISTS last_text_hash TEXT;
-- the last response, AES-256-GCM with a purpose-derived key (it can hold a recovery key shown
-- once); cleared by the worker shortly after the session expires
ALTER TABLE ussd_sessions ADD COLUMN IF NOT EXISTS last_response_ct TEXT;
ALTER TABLE ussd_sessions ADD COLUMN IF NOT EXISTS ended_at TIMESTAMPTZ;
-- set when this session created a ticket (per-phone join limit)
ALTER TABLE ussd_sessions ADD COLUMN IF NOT EXISTS joined_at TIMESTAMPTZ;
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ussd_sessions_scope_pair_chk') THEN
    ALTER TABLE ussd_sessions ADD CONSTRAINT ussd_sessions_scope_pair_chk
      CHECK ((facility_id IS NULL) = (organization_id IS NULL));
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ussd_sessions_facility_org_fk') THEN
    ALTER TABLE ussd_sessions ADD CONSTRAINT ussd_sessions_facility_org_fk
      FOREIGN KEY (facility_id, organization_id) REFERENCES facilities (id, organization_id)
      ON DELETE CASCADE;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ussd_sessions_step_chk') THEN
    ALTER TABLE ussd_sessions ADD CONSTRAINT ussd_sessions_step_chk CHECK (step >= 0);
  END IF;
END $$;
CREATE INDEX IF NOT EXISTS ussd_sessions_phone_joins_idx
  ON ussd_sessions (msisdn_hash, joined_at) WHERE joined_at IS NOT NULL;

-- ---------------------------------------------------------------------------
-- 2. Facility USSD access: opt-in and the public keypad code visitors type
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS facility_ussd_settings (
  facility_id     UUID PRIMARY KEY REFERENCES facilities (id) ON DELETE CASCADE,
  organization_id UUID NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  enabled         BOOLEAN NOT NULL DEFAULT FALSE,
  -- public identifier (shown on posters), never a credential; generated by the server
  access_code     TEXT NOT NULL CHECK (access_code ~ '^[1-9][0-9]{5}$'),
  updated_by      UUID NOT NULL REFERENCES staff_users (id) ON DELETE RESTRICT,
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT facility_ussd_settings_facility_org_fk
    FOREIGN KEY (facility_id, organization_id) REFERENCES facilities (id, organization_id)
    ON DELETE CASCADE
);
CREATE UNIQUE INDEX IF NOT EXISTS facility_ussd_settings_code_idx
  ON facility_ussd_settings (access_code);
CREATE INDEX IF NOT EXISTS facility_ussd_settings_org_idx ON facility_ussd_settings (organization_id);

-- ---------------------------------------------------------------------------
-- 3. Tickets created over USSD are labelled as such (widened CHECK)
-- ---------------------------------------------------------------------------
ALTER TABLE tickets DROP CONSTRAINT IF EXISTS tickets_created_channel_chk;
ALTER TABLE tickets ADD CONSTRAINT tickets_created_channel_chk
  CHECK (created_channel IN ('web', 'staff', 'transfer', 'ussd'));
